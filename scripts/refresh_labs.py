"""Build practical-labs.js: the Trilogy required-practical labs from the GCSE
Chemistry and GCSE Physics sites, renumbered for Combined Science (RP 8-21).

Reads sources/GCSEChemistry/index.html and sources/GCSEPhysics/index.html, the
pinned source pages that refresh_sciences.py downloads (shared-sources.json).
Run:  python scripts/refresh_labs.py   then   node --test tests/course.test.cjs
"""
from pathlib import Path
import re

PROJECT = Path(__file__).resolve().parents[1]
SCRIPT = re.compile(r'<script[^>]*>([\s\S]*?)</script>')

# Separate-science RP number -> Trilogy RP number, and the lab id on the source site.
LABS = {
    'chem': ('GCSEChemistry', 'Chemistry', {1: ('salt', 8), 3: ('elec', 9), 4: ('temp', 10), 5: ('rate', 11), 6: ('chrom', 12), 8: ('water', 13)}),
    'phys': ('GCSEPhysics', 'Physics', {1: ('shc', 14), 3: ('rs', 15), 4: ('iv', 16), 5: ('de', 17), 6: ('sp', 18), 7: ('ac', 19), 8: ('wv', 20), 10: ('ir', 21)}),
}


def scripts(path):
    return [m[1] for m in SCRIPT.finditer(path.read_text(encoding='utf-8'))]


def adapt(code, subject, name, rp):
    remap = {old: new for old, (_, new) in rp.items()}
    code = re.sub(r'(RP\s?|[Rr]equired practical(?: activity)?\s+)(\d+)\b',
                  lambda m: m[1] + str(remap.get(int(m[2]), m[2])), code)
    code = code.replace('AQA GCSE ' + name, 'AQA GCSE Combined Science · ' + name)
    # Each lab registers in its own Practical Lab group with its Trilogy number.
    def reg(m):
        lab = m[1]
        new = next(n for (i, n) in rp.values() if i == lab)
        return f'register({{id:"{lab}",group:"rp-{subject}",num:{new},lvl:"RP {new}",'
    code, n = re.subn(r'register\(\{id:"([a-z]+)",group:"gcse",num:\d+,', reg, code)
    assert n == 1, 'register call not found'
    # Restore recorded datasets before the lab first renders them.
    if 'LabNotebook.observe(' not in code:
        lab = next(i for i, _ in rp.values() if 'id:"'+i+'"' in code)
        code, n = re.subn(r'(const st=\{[\s\S]*?\};)', lambda m: m[0] + '\nLabNotebook.observe("' + lab + '",st);', code, count=1)
        assert n == 1, 'state binding not found'
    return code


def build():
    out = ['/* Generated by scripts/refresh_labs.py from the pinned GCSE Chemistry and GCSE Physics\n'
           '   sites. Edit the source sites, not this file. */\n']
    for subject, (repo, name, rp) in LABS.items():
        src = scripts(PROJECT / 'sources' / repo / 'index.html')
        if subject == 'chem':
            kit = [c for c in src if 'window.GL=(()=>{' in c]
            assert len(kit) == 1, 'chemistry glassware kit not found'
            out.append(kit[0])
        for _, (lab, _new) in sorted(rp.items()):
            found = [c for c in src if re.search(r'register\(\{id:"' + lab + '"', c)]
            assert len(found) == 1, f'{repo}: lab {lab} found {len(found)} times'
            # Course-specific lab overrides are versioned separately so refreshing
            # shared source lessons cannot reintroduce separate-Chemistry content.
            override = PROJECT / 'lab-overrides' / (lab + '.js')
            out.append(override.read_text(encoding='utf-8') if override.exists() else adapt(found[0], subject, name, rp))
    text = '\n'.join(out)
    assert '</script' not in text.lower()
    (PROJECT / 'practical-labs.js').write_text(text, encoding='utf-8')
    print('Wrote practical-labs.js with', sum(len(v[2]) for v in LABS.values()), 'labs')


if __name__ == '__main__':
    build()
